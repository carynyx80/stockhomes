// Generates config/markets.generated.ts: the testnet exchange's 100 city markets.
//   node scripts/gen-markets.mjs
// US: the 79 largest metros in the Zillow Home Value Index (ZHVI, mid-tier, smoothed, seasonally adjusted).
// UK: 21 cities from the UK House Price Index (HM Land Registry, Open Government Licence), average price in GBP,
//     converted to USD at one fixed rate so the market tracks housing, not the currency.
import { writeFileSync } from "node:fs";

const ZILLOW = "https://files.zillowstatic.com/research/public_csvs/zhvi/Metro_zhvi_uc_sfrcondo_tier_0.33_0.67_sm_sa_month.csv";
const US_COUNT = 79;
const UK = [
  ["london", "London", "ENG"],
  ["city-of-westminster", "Westminster", "ENG"],
  ["kensington-and-chelsea", "Kensington & Chelsea", "ENG"],
  ["manchester", "Manchester", "ENG"],
  ["birmingham", "Birmingham", "ENG"],
  ["leeds", "Leeds", "ENG"],
  ["liverpool", "Liverpool", "ENG"],
  ["city-of-bristol", "Bristol", "ENG"],
  ["sheffield", "Sheffield", "ENG"],
  ["newcastle-upon-tyne", "Newcastle", "ENG"],
  ["city-of-nottingham", "Nottingham", "ENG"],
  ["leicester", "Leicester", "ENG"],
  ["southampton", "Southampton", "ENG"],
  ["brighton-and-hove", "Brighton & Hove", "ENG"],
  ["oxford", "Oxford", "ENG"],
  ["cambridge", "Cambridge", "ENG"],
  ["york", "York", "ENG"],
  ["bath-and-north-east-somerset", "Bath", "ENG"],
  ["city-of-edinburgh", "Edinburgh", "SCT"],
  ["cardiff", "Cardiff", "WLS"],
  ["belfast", "Belfast", "NIR"],
];

const slug = (s) => s.toLowerCase().replace(/&/g, "and").replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");

function parseCsvLine(line) {
  const out = [];
  let cur = "";
  let q = false;
  for (const ch of line) {
    if (ch === '"') q = !q;
    else if (ch === "," && !q) {
      out.push(cur);
      cur = "";
    } else cur += ch;
  }
  out.push(cur);
  return out;
}

async function main() {
  const csv = await (await fetch(ZILLOW)).text();
  const rows = csv.trim().split(/\r?\n/).map(parseCsvLine);
  const header = rows[0];
  const metros = rows.slice(1).filter((r) => r[3] === "msa").sort((a, b) => Number(a[1]) - Number(b[1])).slice(0, US_COUNT);
  const us = metros.map((r) => {
    const [name, state] = r[2].split(", ");
    const city = name.replace(/^Urban /, "").replace(/ City$/, (m) => (name === "Boise City" ? "" : m));
    let last = r.length - 1;
    while (last > 5 && !r[last]) last--;
    return { id: `${slug(city)}-${state.toLowerCase()}`, city, region: state, country: "United States", zillow: Number(r[0]), base: Math.round(Number(r[last])), month: header[last].slice(0, 7) };
  });

  const fx = (await (await fetch("https://fred.stlouisfed.org/graph/fredgraph.csv?id=DEXUSUK&cosd=2026-01-01")).text())
    .trim().split(/\r?\n/).slice(1).map((l) => l.split(",")).filter(([, v]) => v && v !== ".").at(-1);
  const gbpUsd = Math.round(Number(fx[1]) * 100) / 100;

  const query = `PREFIX ukhpi: <http://landregistry.data.gov.uk/def/ukhpi/>
SELECT ?r ?month ?p WHERE {
  VALUES ?r { ${UK.map(([r]) => `"${r}"`).join(" ")} }
  BIND(IRI(CONCAT("http://landregistry.data.gov.uk/id/region/", ?r)) AS ?region)
  ?obs ukhpi:refRegion ?region ; ukhpi:refMonth ?month ; ukhpi:averagePrice ?p .
  FILTER (?month >= "2026-01"^^<http://www.w3.org/2001/XMLSchema#gYearMonth>)
}`;
  const res = await fetch("https://landregistry.data.gov.uk/landregistry/sparql", {
    method: "POST",
    headers: { "content-type": "application/x-www-form-urlencoded", accept: "application/sparql-results+json" },
    body: new URLSearchParams({ query }).toString(),
  });
  const latest = {};
  for (const b of (await res.json()).results.bindings) {
    const r = b.r.value;
    if (!latest[r] || b.month.value > latest[r].month) latest[r] = { month: b.month.value.slice(0, 7), p: Number(b.p.value) };
  }
  const uk = UK.map(([region, city, nation]) => {
    if (!latest[region]) throw new Error(`no UK HPI for ${region}`);
    return { id: `${slug(city)}-uk`, city, region: nation, country: "United Kingdom", ukhpi: region, base: Math.round(latest[region].p * gbpUsd), month: latest[region].month };
  });

  const all = [...us, ...uk];
  const ids = new Set(all.map((m) => m.id));
  if (ids.size !== all.length) throw new Error("duplicate market ids");
  for (const m of all) if (m.id.length > 31) throw new Error(`id too long for bytes32: ${m.id}`);

  const line = (m) =>
    `  { id: ${JSON.stringify(m.id)}, city: ${JSON.stringify(m.city)}, region: ${JSON.stringify(m.region)}, country: ${JSON.stringify(m.country)}, ` +
    (m.zillow ? `source: { kind: "zillow", regionId: ${m.zillow} }` : `source: { kind: "ukhpi", region: ${JSON.stringify(m.ukhpi)} }`) +
    `, base: ${m.base} },`;
  const out = `// Generated by scripts/gen-markets.mjs on ${new Date().toISOString().slice(0, 10)}. Do not edit by hand.
// base: the latest reading in USD when generated (US ${us[0].month}, UK ${uk[0].month}); used for the opening oracle price.
import type { CatalogueMarket } from "./markets";

/** GBP→USD used for every UK market (FRED DEXUSUK, ${fx[0]}). Fixed, so UK markets track housing, not FX. */
export const GBP_USD = ${gbpUsd};

export const CATALOGUE: CatalogueMarket[] = [
${all.map(line).join("\n")}
];
`;
  writeFileSync(new URL("../config/markets.generated.ts", import.meta.url), out);
  console.log(`wrote ${all.length} markets (${us.length} US, ${uk.length} UK), GBP/USD ${gbpUsd}`);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
