// Regenerates lib/exchange/abis.ts from Foundry's build output, so the site's ABIs always match the contracts.
//   cd contracts && forge build && node export-abis.mjs
import { readFileSync, writeFileSync } from "node:fs";
const names = ["PriceOracle", "StoxhomesVault", "StoxhomesPerps", "TestUSDG"];
const files = { TestUSDG: "testnet/TestUSDG.sol" };
let out = "// Generated by contracts/export-abis.mjs from the compiled contracts. Do not edit by hand.\n\n";
for (const n of names) {
  const json = JSON.parse(readFileSync(new URL(`./out/${(files[n] ?? `${n}.sol`).split("/").pop()}/${n}.json`, import.meta.url)));
  out += `export const ${n[0].toLowerCase()}${n.slice(1)}Abi = ${JSON.stringify(json.abi, null, 2)} as const;\n\n`;
}
writeFileSync(new URL("../lib/exchange/abis.ts", import.meta.url), out);
console.log("wrote lib/exchange/abis.ts");
